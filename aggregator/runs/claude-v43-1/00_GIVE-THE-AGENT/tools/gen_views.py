#!/usr/bin/env python3
"""gen_views.py, v40: regenerate out/_views/ and out/_wiki/ from canonical files. Run by done.sh at
every close; never edited by hand. Every file carries the sha256 of its sources in its header.

    python3 tools/gen_views.py NN [--root .] [--out out]

Writes (when the sources exist):
  _views/data-structure.tsv / .md   quote, first-order concept, second-order theme, third-order
                                    theme, fourth-order theme, aggregate dimension; one row per
                                    first-order concept in the store. Above 2 MB the .md holds only
                                    a note: read the rows with mem.py view data-structure --room S
  _views/rooms-x-third.tsv          rooms by third-order themes (count of second-order themes placed)
  _views/rooms-x-elements.tsv       rooms by model elements (the op, from the ledger)
  _views/adaptations-current.tsv    current op, adjudication, observation and revised text
  _views/local-accounts.tsv         local adequacy and return-version status by room
  _views/relations.tsv              room, other, direction, label (from store relations.jsonl)
  _views/transitions.tsv            room, from_theme, to_theme, interval (from the ledger)
  _views/moves.tsv                  moves per stage from tier_history.jsonl and model/history.jsonl
  _wiki/rooms/<sub>.md              the room's column
  _wiki/model/<id>.md               an element: statement, evidence, adaptations touching it
  _views/figure-model.md            the model drawn twice in Mermaid, with and without the theorised
                                    arrows (stage C5 section 10)
  and, after stage D3, calls distance.py for the adaptation matrices and the distance.
"""
import argparse, collections, hashlib, json, os, re, subprocess, sys
from adaptation_ledger import effective_lines, effective_rooms, ledger_provenance
import vlib

MD_CEILING = 2 * 1024 * 1024
BREAKS = re.compile(r"[\t\r\n\v\f\x1c-\x1e\x85\u2028\u2029]")


def tsv_cell(x):
    """One tsv cell: no tab and nothing a reader splits lines on (\\r, \\u2028, ...)."""
    return BREAKS.sub(" ", str(x))

def jl(p):
    if not os.path.exists(p):
        return []
    with open(p, encoding="utf-8") as f:
        return [json.loads(l) for l in f if l.strip()]

def sha(p):
    return hashlib.sha256(open(p, "rb").read()).hexdigest()[:16] if os.path.exists(p) else "absent"

def header(sources):
    return "# generated by gen_views.py; sources: " + "; ".join("%s %s" % (os.path.basename(s), sha(s)) for s in sources)

def tsv(path, rows, cols, sources):
    with open(path, "w", encoding="utf-8") as f:
        f.write(header(sources) + "\n" + "\t".join(cols) + "\n")
        for r in rows:
            f.write("\t".join("" if x is None else tsv_cell(x) for x in r) + "\n")

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("stage")
    ap.add_argument("--root", default=".")
    ap.add_argument("--out", default=None)
    a = ap.parse_args()
    out = a.out or os.path.join(a.root, "out")
    S = os.path.join(a.root, "package", "store")
    V = os.path.join(out, "_views"); W = os.path.join(out, "_wiki")
    for d in (V, os.path.join(W, "rooms"), os.path.join(W, "model")):
        os.makedirs(d, exist_ok=True)
    codes = jl(os.path.join(S, "codes.jsonl")); themes = jl(os.path.join(S, "themes.jsonl"))
    theme_by = {(t["sub"], t["theme_id"]): t for t in themes}
    placed = {}
    ap_ = os.path.join(out, "assignments_final.jsonl")
    for r in jl(ap_):
        so = r.get("third_order"); placed[(r["sub"], r["theme_id"])] = so if isinstance(so, list) else [so]
    scheme = {}
    # the latest frozen scheme, else the working scheme_current (out/scheme/ or out/), as mem.py reads it
    for f in ("scheme_v2.jsonl", "scheme_final.jsonl", "scheme.jsonl", "scheme/scheme_current.jsonl", "scheme_current.jsonl"):
        p = os.path.join(out, f)
        if os.path.exists(p):
            for r in jl(p):
                i = r.get("id") or r.get("theme")
                if i:
                    scheme[i] = dict(r, id=i, name=r.get("name") or r.get("label"))
            break
    fourth_of = {}
    for r in jl(os.path.join(out, "fourth", "fourth.jsonl")):
        for m in r.get("members", []): fourth_of[m] = (r["id"], r.get("name"))
    dim_of = {}
    for r in jl(os.path.join(out, "dimensions.jsonl")):
        for m in r.get("members", []): dim_of[m] = (r["id"], r.get("label"))
    # data structure
    rows = []
    for c in codes:
        t = theme_by.get((c["sub"], c.get("theme_id")))
        t3 = (placed.get((c["sub"], c.get("theme_id")), [None]) or [None])[0]
        t4 = fourth_of.get(t3, (None, None))
        d = dim_of.get(t4[0], (None, None))
        rows.append([c["sub"], c["code_id"], tsv_cell(c.get("text") or ""),
                     c.get("first_order"), c.get("theme_id"), t.get("second_order") if t else None,
                     t3, scheme.get(t3, {}).get("name"), t4[0], t4[1], d[0], d[1]])
    tsv(os.path.join(V, "data-structure.tsv"), rows,
        ["room", "code_id", "quote", "first_order", "theme_id", "second_order", "third_id", "third", "fourth_id", "fourth", "dim_id", "dimension"],
        [os.path.join(S, "codes.jsonl"), os.path.join(S, "themes.jsonl"), ap_, os.path.join(out, "fourth", "fourth.jsonl"), os.path.join(out, "dimensions.jsonl")])
    md = [header([os.path.join(S, "codes.jsonl"), ap_]), "", "| quote | 1st | 2nd | 3rd | 4th | dimension |", "|---|---|---|---|---|---|"]
    size = 0
    for r in rows:
        md.append("| %s | %s | %s | %s | %s | %s |" % tuple(tsv_cell(x or "").replace("|", "/") for x in (r[2][:120], r[3], r[5], r[7] or r[6], r[9], r[11])))
        size += len(md[-1].encode("utf-8")) + 1
        if size > MD_CEILING:
            break
    with open(os.path.join(V, "data-structure.md"), "w", encoding="utf-8") as f:
        if size > MD_CEILING:
            f.write("%s\n\nThe data structure is over 2 MB as a table (%d concepts), so it is not written here. "
                    "The rows are in data-structure.tsv; read them a page at a time with\n\n"
                    "    python3 tools/mem.py view data-structure --room <sub> [--grep <re>]\n"
                    "    python3 tools/mem.py table --from 3rd | --from 2nd | --room <sub>\n" % (md[0], len(rows)))
        else:
            f.write("\n".join(md) + "\n")
    # rooms x third
    rooms = sorted({c["sub"] for c in codes} | {t["sub"] for t in themes})
    thirds = sorted(scheme) if scheme else sorted({x for v in placed.values() for x in v if x})
    cnt = collections.Counter()
    for (sub, tid), so in placed.items():
        for x in so:
            cnt[(sub, x)] += 1
    tsv(os.path.join(V, "rooms-x-third.tsv"), [[r] + [cnt.get((r, t), 0) for t in thirds] for r in rooms], ["room"] + thirds, [ap_])
    # Current adjudicated returns, including local particulars and explicit uncertainty.
    ledger = effective_lines(out, include_particular=True, include_pending=True)
    current_returns = effective_rooms(out)
    local_states = vlib.local_return_states(out)
    ledger_sources = [os.path.join(out, name) for name in ledger_provenance(out)]
    els = sorted({l.get("element") for l in ledger if l.get("element")})
    cell = {}
    for l in ledger:
        key = (l["sub"], l.get("element"))
        # Keep the established op-only matrix schema. Qualifiers belong in the
        # detailed view below; an absent op alone is not evidence of absence.
        value = l["op"]
        cell[key] = (cell.get(key, "") + "," + value).strip(",")
    tsv(os.path.join(V, "rooms-x-elements.tsv"),
        [[r] + [cell.get((r, e), "") for e in els] for r in sorted(current_returns)],
        ["room"] + els, ledger_sources)
    tsv(os.path.join(V, "adaptations-current.tsv"),
        [[l["sub"], l["id"], l.get("element"), l["op"], l.get("decision"),
          l.get("kind"), l.get("observation"), l.get("condition"),
          l.get("statement"), l.get("how"), l.get("current_model_version"),
          l.get("source_ledger")] for l in ledger],
        ["room", "adaptation_id", "element", "op", "decision", "kind", "observation",
         "condition", "statement", "how", "model_version", "source_ledger"], ledger_sources)
    tsv(os.path.join(V, "local-accounts.tsv"),
        [[r, local_states.get(r,{}).get("local_status", "unreturned"),
          local_states.get(r,{}).get("version_status", "no-return"),
          current_returns.get(r,{}).get("phase"), current_returns.get(r,{}).get("model_version")]
         for r in sorted(set(rooms) | set(current_returns))],
        ["room", "local_status", "version_status", "phase", "return_model_version"], ledger_sources)
    if current_returns and a.stage in ("D3", "D4", "D5", "D6", "E1", "E2"):
        subprocess.run([sys.executable, os.path.join(os.path.dirname(__file__), "distance.py"), "--out", out], check=True)
    # relations, transitions, moves
    rel = jl(os.path.join(S, "relations.jsonl"))
    if rel:
        tsv(os.path.join(V, "relations.tsv"), [[r.get("sub"), r.get("other"), r.get("direction"), r.get("label"), r.get("adjacent")] for r in rel],
            ["room", "other", "direction", "label", "adjacent"], [os.path.join(S, "relations.jsonl")])
    tr = jl(os.path.join(S, "transitions.jsonl"))
    if tr:
        tsv(os.path.join(V, "transitions.tsv"), [[r.get("sub"), ",".join(r.get("from_case_themes", r.get("from_themes", []))), ",".join(r.get("to_case_themes", r.get("to_themes", []))), r.get("interval_s")] for r in tr],
            ["room", "from", "to", "interval_s"], [os.path.join(S, "transitions.jsonl")])
    moves = collections.Counter()
    for r in jl(os.path.join(out, "tier_history.jsonl")) + jl(os.path.join(out, "model", "history.jsonl")):
        moves[(r.get("stage"), r.get("move"))] += 1
    tsv(os.path.join(V, "moves.tsv"), [[s, m, n] for (s, m), n in sorted(moves.items(), key=lambda x: (str(x[0][0]), str(x[0][1])))],
        ["stage", "move", "n"], [os.path.join(out, "tier_history.jsonl"), os.path.join(out, "model", "history.jsonl")])
    # wiki: rooms
    by_room = collections.defaultdict(list)
    for r in rows: by_room[r[0]].append(r)
    led_by_room = collections.defaultdict(list)
    for l in ledger: led_by_room[l["sub"]].append(l)
    for sub in rooms:
        with open(os.path.join(W, "rooms", sub + ".md"), "w", encoding="utf-8") as f:
            f.write("# r/%s\n%s\n\n## second-order themes and their placements\n" % (sub, header([ap_])))
            seen = set()
            for r in by_room[sub]:
                if r[4] in seen: continue
                seen.add(r[4]); f.write("- %s %s -> %s %s -> %s -> %s\n" % (r[4], r[5], r[6] or "unplaced", r[7] or "", r[9] or "", r[11] or ""))
            state = local_states.get(sub, {})
            f.write("\n## local account\n%s; version: %s; return: %s\n%s\n" % (
                state.get("local_status", "unreturned"), state.get("version_status", "no-return"),
                state.get("model_version", "none"), header(ledger_sources)))
            if led_by_room[sub]:
                f.write("\n## adaptations\n")
                for l in led_by_room[sub]:
                    f.write("- %s %s %s: %s [%s]\n" % (l["op"], l.get("element") or "", l.get("source") or "", (l.get("condition") or l.get("statement") or "") + " " + str(l.get("how") or ""), str(l.get("decision")) + ";" + str(l.get("kind")) + ";" + str(l.get("observation") or "")))
    # wiki: elements
    for e in jl(os.path.join(out, "model", "elements.jsonl")):
        with open(os.path.join(W, "model", e["id"] + ".md"), "w", encoding="utf-8") as f:
            f.write("# %s (%s)\n%s\n\n%s\n\ntier %s; dimension %s; status %s; since %s\n\n" % (
                e["id"], e.get("kind"), header([os.path.join(out, "model", "elements.jsonl")]), e.get("statement"), e.get("tier"), e.get("dimension"), e.get("status"), e.get("since")))
            ev = e.get("evidence") or {}
            f.write("evidence: findings %s; codes %s\n" % (",".join(ev.get("findings", [])), ",".join(ev.get("codes", []))))
            touching = [l for l in ledger if l.get("element") == e["id"]]
            if touching:
                f.write("\n## adaptations touching it (%d)\n" % len(touching))
                for l in touching[:200]:
                    f.write("- %s %s %s: %s\n" % (l["sub"], l["op"], l.get("source") or "", (l.get("condition") or l.get("statement") or "") + " " + str(l.get("how") or "") + " [" + str(l.get("decision")) + "]"))
    figure(out, V)
    print("views regenerated for stage %s: %d concepts, %d rooms, %d ledger lines" % (a.stage, len(rows), len(rooms), len(ledger)))
    return 0


SIDE = {"condition": "conditions", "process": "what the rooms did", "role": "what the rooms did",
        "claim": "what follows"}


def figure(out, V):
    """_views/figure-model.md: the model drawn from model/ and propositions.jsonl (stage C5 section 10), twice, in
    Mermaid: every arrow a proposition carries, and then only those that are not
    theorised: an arrow whose own grounding is not reading-alone. An arrow no proposition carries, or with no instance, is not drawn. The text beside it is the
    analyst's, in figure-C5.md."""
    els = {e["id"]: e for e in jl(os.path.join(out, "model", "elements.jsonl")) if e.get("status") != "withdrawn"}
    ars = {r["id"]: r for r in jl(os.path.join(out, "model", "arrows.jsonl"))
           if r.get("in_model") and r.get("status") != "withdrawn"
           and (r.get("support") or r.get("support_transition"))}
    props = jl(os.path.join(out, "propositions.jsonl"))
    if not els or not props:
        return
    carried = collections.defaultdict(list)
    for p in props:
        for aid in p.get("rests_on") or []:
            if aid in ars:
                carried[aid].append(p)

    def draw(keep):
        drawn = {a: ps for a, ps in carried.items() if keep(a)}
        nodes = sorted({ars[a].get(x) for a in drawn for x in ("from", "to")} & set(els))
        L = ["```mermaid", "flowchart LR"]
        for side in ("conditions", "what the rooms did", "what follows"):
            members = [n for n in nodes if SIDE.get(els[n].get("kind")) == side]
            if members:
                L.append('  subgraph %s["%s"]' % (side.replace(" ", "_"), side))
                for n in members:
                    L.append('    %s["%s: %s"]' % (n, n, str(els[n].get("statement") or "").replace('"', "'")[:80]))
                L.append("  end")
        for a in sorted(drawn):
            r = ars[a]
            L.append('  %s -->|"%s %s"| %s' % (r.get("from"), a, " ".join(sorted(p["id"] for p in drawn[a])), r.get("to")))
        L.append("```")
        return L, len(drawn)

    with_t, n1 = draw(lambda a: True)
    # the arrow's own grounding decides, not the propositions it sits in (audit 2026-09-29b)
    without_t, n2 = draw(lambda a: str(ars[a].get("grounding") or "") != "reading-alone")
    src = [os.path.join(out, "model", "elements.jsonl"), os.path.join(out, "model", "arrows.jsonl"),
           os.path.join(out, "propositions.jsonl")]
    src = [x for x in src if os.path.exists(x)]
    with open(os.path.join(V, "figure-model.md"), "w", encoding="utf-8") as f:
        f.write("# The model, drawn from model/\n%s\n\n## With the theorised arrows (%d)\n\n%s\n\n"
                "## Without the theorised arrows (%d)\n\n%s\n"
                % (header(src), n1, "\n".join(with_t), n2, "\n".join(without_t)))

if __name__ == "__main__":
    sys.exit(main())

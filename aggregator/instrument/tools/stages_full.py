#!/usr/bin/env python3
"""stages_full.py: assemble STAGES-full.md, the one document that holds every stage file whole,
for the operator. The analyst never receives it; the analyst receives one stage file per stage.

    python3 tools/stages_full.py [--root INSTRUMENT]
"""
import argparse, glob, os, re

ap = argparse.ArgumentParser(); ap.add_argument("--root", default=".")
a = ap.parse_args()
files = sorted(glob.glob(os.path.join(a.root, "stages", "STAGE-*.md")),
               key=lambda p: os.path.basename(p))
parts, index = [], []
total = 0
for p in files:
    txt = open(p, encoding="utf-8").read().rstrip() + "\n"
    words = len(txt.split()); total += words
    m = re.match(r"#\s*(.+)", txt)
    title = m.group(1).strip() if m else os.path.basename(p)
    anchor = re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")
    index.append("- [%s](#%s), %d words, `stages/%s`" % (title, anchor, words, os.path.basename(p)))
    parts.append(txt)
head = ("# The stages of the v43 aggregator, whole\n\n"
        "Generated by `tools/stages_full.py` from `stages/STAGE-*.md`; edit the stage files, never "
        "this file. The operator's copy: every stage file follows in order, unchanged. The analyst "
        "receives one stage file at a time (STANDING-INSTRUCTIONS.md, the startup packet). The stage "
        "table with models and outputs is CONTRACT-aggregator.md §6; the fleet pattern is FLEET.md; "
        "the return at stage D is SCHEMA-adaptations.md.\n\n%d files, %d words.\n\n## Index\n\n%s\n\n---\n\n"
        % (len(files), total, "\n".join(index)))
out = os.path.join(a.root, "STAGES-full.md")
open(out, "w", encoding="utf-8").write(head + "\n---\n\n".join(parts))
print("%s: %d files, %d words" % (out, len(files), total))

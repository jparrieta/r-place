#!/usr/bin/env python3
"""gen_platform.py (v41): writes the analyst's two platform files from the two schedules.

    python3 aggregator/handler/claude/gen_platform.py            # from the repository root
    python3 aggregator/handler/claude/gen_platform.py --check    # exit 1 if a platform file is stale

instrument/PLATFORM-claude.md from arm.claude.json, instrument/PLATFORM-codex.md from
arm.codex.json (both beside this script). Everything else in instrument/ is the same on both platforms; the model,
the effort, the reader routes and how a leg is opened and closed live here and in the arm files.
CLAUDE.md (read by Claude Code) and AGENTS.md (read by Codex) each point to their own file.
"""
import json, os, sys
H = os.path.dirname(os.path.abspath(__file__)); A = os.path.join(os.path.dirname(os.path.dirname(H)), "instrument")
ORDER = "A1 B1 B2 B3 B4 C1 C2 C3 C4 C5 D1 D2 D3 D4 D5 D6 E1 E2".split()

def table(arm):
    rows = ["| stage | analyst | effort | readers |", "|---|---|---|---|"]
    for s in ORDER:
        e = arm.get(s, {})
        eff = e.get("effort", "")
        if e.get("legs"):
            eff = "; ".join("%s %s" % (k, v.get("effort", eff)) for k, v in sorted(e["legs"].items()))
        r = e.get("readers") or {}
        rd = ("%s x%s via %s%s" % (r.get("model"), r.get("n"), r.get("route"), (", effort " + r["effort"]) if r.get("effort") else "")) if r else ""
        rows.append("| %s | %s | %s | %s |" % (s, e.get("analyst", ""), eff, rd))
    return "\n".join(rows)

TEXT = {
"claude": """# Your platform: Claude

Read this once, at stage A1, after AGENT.md. The method, the stage files, the tools and the
checks are the same on both platforms; this file is where they differ. Generated by
`aggregator/handler/claude/gen_platform.py` from `aggregator/handler/claude/arm.claude.json`; never edit it by hand.

## Models and routes

`CONTROL/arm.json` (a copy of `arm.claude.json`) sets each leg's model and effort; the harness
launches you with them and checks the served model at every close. You never change model or
route inside a session.

{table}

- **The routine readers** (B2, B3, B4, D2's verdict fleet, E1's reconstruction readers) run on
  `@preset/cheap` through the gateway, the OpenRouter route the operator's `tools/fleet.py`
  sends packets on (`dispatch.sh`).
- **The reviewers** of C2 and C5 run on Opus through the Claude CLI on the subscription, each in a
  session of its own, sent by the same `fleet.py`.
- **The labelers** at D2 are GPT case leads in Codex on both platforms (`handoff/HANDLER.md`).

## Legs, closes and compaction

- The operator opens a leg with `harness/step.sh` and closes it with `harness/close.sh` after
  you stop. Each ordinary leg continues the last close's conversation, forked from its committed
  checkpoint, in the same folder; the startup packet orients that continuation.
- `done.sh` is your exit. The harness's `close.sh` then takes the snap of `out/`, asks the recall
  probe's questions in a fork of your session (your transcript is untouched), scores them and
  checkpoints the leg.
- Compaction is owned by the harness (`CLAUDE.md`): after one, it refuses work until you have
  re-read the head, the stage file and the diary.
- A pause comes from `pause.sh`, when the subscription week runs short or for any other reason.
""",
"codex": """# Your platform: Codex

Read this once, at stage A1, after AGENT.md and OPENAI-RUNTIME.md. The method, the stage files,
the tools and the checks are the same on both platforms; this file is where they differ.
Generated by `aggregator/handler/claude/gen_platform.py` from `aggregator/handler/claude/arm.codex.json`; never edit it by hand.

## Models and routes

`aggregator/handler/claude/arm.codex.json` sets each leg's model and effort; the controller (`aggregator/handler/codex/run.py`,
`aggregator/handler/codex/runtime/`) records the native identities at every close. Never change the model to
escape a failure.

{table}

- **The routine readers** run on `gpt-6-sol` as independent native readers the controller owns,
  or on OpenRouter when the study selected that fleet arm (`aggregator/handler/claude/fleet-arms.json`,
  `FLEET-ARMS.md`). Wherever the stage files speak of `fleet.py`, read the controller's dispatch:
  it applies the same return validation (`tools/fleet.py`'s `validate`).
- **The reviewers** of C2 and C5 run on `gpt-6-astra`, each in a session of its own.
- **The labelers** at D2 resume each room's original case lead in Codex (`handoff/HANDLER.md`).

## Legs, closes and compaction

- Each ordinary leg forks the preceding completed native checkpoint and its files. `_head.md`
  and the diary orient that continuation; they do not replace the history.
- `done.sh` is your exit. The controller then runs the trusted checks and the recall probe,
  records the native boundary and commits the compressed checkpoint. Closing at `packets-out`
  asks the controller to dispatch; never run a fleet yourself.
- The shell starts in `out/`: `cd ..` before running the tools. Scratch and cache paths are the
  controller's.
- At a safe pause, log the working hypothesis and the next item with `mem.py log --kind pause`,
  then `bash tools/done.sh STAGE --pause`. The controller owns interruption and recovery.
"""}

def render(p):
    arm = json.load(open(os.path.join(H, "arm.%s.json" % p)))
    return TEXT[p].replace("{table}", table(arm))

check = "--check" in sys.argv; stale = []
for p in ("claude", "codex"):
    out = os.path.join(A, "PLATFORM-%s.md" % p); t = render(p)
    if check:
        if not os.path.exists(out) or open(out).read() != t: stale.append(out)
    else:
        open(out, "w").write(t); print("wrote", os.path.relpath(out, os.path.dirname(H)))
if check:
    print("stale: " + ", ".join(stale) if stale else "platform files current"); sys.exit(1 if stale else 0)
